import { eq } from 'drizzle-orm';
import sharp from 'sharp';
import { createAdminClient } from '@/lib/supabase/admin';
import { productImages } from '../db/schema';
import type { Tx } from './posting';

/**
 * Turning an uploaded original into the two stored derivatives and the
 * `product_images` row, per docs/04-engineering/media-pipeline.md.
 *
 * The browser can only upload to the private staging bucket using a short-
 * lived signed token issued by an authorized server action. This function
 * validates and converts that uploaded object before storing public assets.
 */

export const PRODUCT_UPLOAD_BUCKET = 'nextly-product-staging';
export const PRODUCT_IMAGE_BUCKET = 'nextly-product-images';
export const MAX_PRODUCT_IMAGE_BYTES = 10 * 1024 * 1024;
export const ALLOWED_PRODUCT_IMAGE_FORMATS = new Set(['jpeg', 'png', 'webp', 'avif']);
const DISPLAY_WIDTH = 1600;
const THUMB_WIDTH = 400;
const QUALITY = 75;

export async function recordProductImage(
  tx: Tx,
  input: {
    productId: string;
    uploadPathname: string;
    alt?: string | null;
  },
): Promise<{ id: string } | null> {
  const uploadPrefix = `products/${input.productId}/`;
  if (
    !input.uploadPathname.startsWith(uploadPrefix) ||
    !/^[0-9a-f-]{36}$/i.test(input.uploadPathname.slice(uploadPrefix.length))
  ) {
    throw new Error('Uploaded image path is outside the requested product.');
  }

  // The upload path is generated by the server and is also the retry key.
  const [existing] = await tx
    .select({ id: productImages.id })
    .from(productImages)
    .where(eq(productImages.sourcePathname, input.uploadPathname))
    .limit(1);
  if (existing) {
    await removeStoredObject(PRODUCT_UPLOAD_BUCKET, input.uploadPathname);
    return existing;
  }

  const storage = createAdminClient().storage;
  const { data: sourceBlob, error: downloadError } = await storage
    .from(PRODUCT_UPLOAD_BUCKET)
    .download(input.uploadPathname);
  if (downloadError || !sourceBlob) {
    throw new Error('The temporary image upload could not be read. Please upload it again.');
  }
  if (sourceBlob.size === 0 || sourceBlob.size > MAX_PRODUCT_IMAGE_BYTES) {
    await removeStoredObject(PRODUCT_UPLOAD_BUCKET, input.uploadPathname);
    throw new Error('The uploaded image is empty or exceeds the 10 MB limit.');
  }

  const derivativePathnames: string[] = [];
  try {
    const source = Buffer.from(await sourceBlob.arrayBuffer());
    const image = sharp(source, { limitInputPixels: 40_000_000, failOn: 'error' });
    const metadata = await image.metadata();
    if (!metadata.format || !ALLOWED_PRODUCT_IMAGE_FORMATS.has(metadata.format)) {
      throw new Error('Only JPEG, PNG, WebP or AVIF images are accepted.');
    }
    if (!metadata.width || !metadata.height) {
      throw new Error('The uploaded file is not a valid image.');
    }

    const [{ data: displayData, info: displayInfo }, thumbData] = await Promise.all([
      image
        .clone()
        .rotate()
        .resize({
          width: DISPLAY_WIDTH,
          height: DISPLAY_WIDTH,
          fit: 'inside',
          withoutEnlargement: true,
        })
        .avif({ quality: QUALITY })
        .toBuffer({ resolveWithObject: true }),
      image
        .clone()
        .rotate()
        .resize({
          width: THUMB_WIDTH,
          height: THUMB_WIDTH,
          fit: 'inside',
          withoutEnlargement: true,
        })
        .webp({ quality: QUALITY })
        .toBuffer(),
    ]);
    const assetStem = `products/${input.productId}/${crypto.randomUUID()}`;
    const displayPathname = `${assetStem}-1600.avif`;
    const thumbPathname = `${assetStem}-400.webp`;
    derivativePathnames.push(displayPathname, thumbPathname);

    const uploads = await Promise.all([
      storage.from(PRODUCT_IMAGE_BUCKET).upload(displayPathname, displayData, {
        contentType: 'image/avif',
        cacheControl: '31536000',
        upsert: false,
      }),
      storage.from(PRODUCT_IMAGE_BUCKET).upload(thumbPathname, thumbData, {
        contentType: 'image/webp',
        cacheControl: '31536000',
        upsert: false,
      }),
    ]);
    const uploadError = uploads.find((result) => result.error)?.error;
    if (uploadError)
      throw new Error('The optimized product images could not be stored. Please retry.');

    const displayUrl = storage.from(PRODUCT_IMAGE_BUCKET).getPublicUrl(displayPathname)
      .data.publicUrl;
    const thumbUrl = storage.from(PRODUCT_IMAGE_BUCKET).getPublicUrl(thumbPathname)
      .data.publicUrl;
    const [row] = await tx
      .select({ max: productImages.position })
      .from(productImages)
      .where(eq(productImages.productId, input.productId))
      .orderBy(productImages.position)
      .limit(1);
    const isFirst = !row;

    const [inserted] = await tx
      .insert(productImages)
      .values({
        productId: input.productId,
        url: displayUrl,
        blobPathname: displayPathname,
        sourcePathname: input.uploadPathname,
        thumbUrl,
        thumbPathname,
        width: displayInfo.width,
        height: displayInfo.height,
        alt: input.alt ?? null,
        byteSize: displayData.byteLength,
        position: isFirst ? 0 : await nextPosition(tx, input.productId),
        isPrimary: isFirst,
      })
      .returning({ id: productImages.id });

    await removeStoredObject(PRODUCT_UPLOAD_BUCKET, input.uploadPathname);
    return inserted ?? null;
  } catch (error) {
    await removeStoredObjects(PRODUCT_IMAGE_BUCKET, derivativePathnames);
    await removeStoredObject(PRODUCT_UPLOAD_BUCKET, input.uploadPathname);
    throw error;
  }
}

async function nextPosition(tx: Tx, productId: string): Promise<number> {
  const rows = await tx
    .select({ position: productImages.position })
    .from(productImages)
    .where(eq(productImages.productId, productId));
  return rows.reduce((max, r) => Math.max(max, r.position), -1) + 1;
}

/** Delete both derivatives before the row itself is removed. */
export async function deleteProductImageBlobs(image: {
  blobPathname: string;
  thumbPathname: string | null;
}): Promise<void> {
  const pathnames = [image.blobPathname, image.thumbPathname].filter(
    (value): value is string => typeof value === 'string' && !value.startsWith('http'),
  );
  await removeStoredObjects(PRODUCT_IMAGE_BUCKET, pathnames);
}

async function removeStoredObject(bucket: string, pathname: string): Promise<void> {
  await removeStoredObjects(bucket, [pathname]);
}

async function removeStoredObjects(bucket: string, pathnames: string[]): Promise<void> {
  if (pathnames.length === 0) return;
  try {
    const { error } = await createAdminClient().storage.from(bucket).remove(pathnames);
    if (error)
      console.error(`[media] could not remove ${pathnames.length} object(s) from ${bucket}`);
  } catch {
    console.error(`[media] could not reach Storage to remove ${pathnames.length} object(s)`);
  }
}
